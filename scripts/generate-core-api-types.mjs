// Generate wire types from the embedded core OpenAPI source. No network or deps.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const contractPath = new URL('../backend/internal/api/openapi/core.json', import.meta.url);
const outputPath = new URL('../frontend/src/api/coreTypes.ts', import.meta.url);
const spec = JSON.parse(readFileSync(contractPath, 'utf8'));

function type(schema) {
  let result;
  if (schema.$ref) result = schema.$ref.split('/').at(-1);
  else if (schema.enum) result = schema.enum.map(value => JSON.stringify(value)).join(' | ');
  else if (schema.type === 'string') result = 'string';
  else if (schema.type === 'integer' || schema.type === 'number') result = 'number';
  else if (schema.type === 'boolean') result = 'boolean';
  else if (schema.type === 'array') result = `Array<${type(schema.items)}>`;
  else if (schema.type === 'object') {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(([name, child]) =>
      `  ${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${type(child)};`);
    if (schema.additionalProperties === true) fields.push('  [key: string]: unknown;');
    result = `{\n${fields.join('\n')}\n}`;
  } else throw new Error(`Unsupported contract schema: ${JSON.stringify(schema)}`);
  return schema.nullable ? `${result} | null` : result;
}
const lines = [
  '// Generated by scripts/generate-core-api-types.mjs; edit openapi/core.json.',
  '// This file describes wire shapes. Authority and validation remain server-side.', '',
];
for (const [name, schema] of Object.entries(spec.components.schemas)) {
  lines.push(`export type ${name} = ${type(schema)};`, '');
}
lines.push('export interface CoreOperations {');
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    const request = operation.requestBody?.content?.['application/json']?.schema;
    const responses = Object.entries(operation.responses).map(([status, response]) => {
      const schema = response.content?.['application/json']?.schema;
      return `${JSON.stringify(status)}: ${schema ? type(schema) : 'undefined'};`;
    });
    lines.push(`  ${operation.operationId}: {`,
      `    method: ${JSON.stringify(method.toUpperCase())};`,
      `    path: ${JSON.stringify(path)};`,
      `    request: ${request ? type(request) : 'undefined'};`,
      `    responses: { ${responses.join(' ')} };`, '  };');
  }
}
lines.push('}', '');
const generated = lines.join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== generated) {
    throw new Error('Generated core API types are stale. Run node scripts/generate-core-api-types.mjs.');
  }
} else {
  writeFileSync(outputPath, generated);
  console.log(`Generated ${fileURLToPath(outputPath)}`);
}
